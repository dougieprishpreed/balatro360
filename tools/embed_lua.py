#!/usr/bin/env python3
"""Embeds src/lua/*.lua into src/runtime/embedded_lua.h as byte arrays.

The generated header is committed so the Xbox 360 build (Visual Studio /
XDK) does not need Python. Re-run this after editing any file in src/lua:

    python3 tools/embed_lua.py
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src", "lua")
OUT = os.path.join(ROOT, "src", "runtime", "embedded_lua.h")
FILES = ["common.lua", "hooks.lua", "boot.lua"]


def main():
    out = []
    out.append("// Generated by tools/embed_lua.py from src/lua/. Do not edit.")
    out.append("#ifndef B360_EMBEDDED_LUA_H")
    out.append("#define B360_EMBEDDED_LUA_H")
    out.append("")
    for name in FILES:
        data = open(os.path.join(SRC, name), "rb").read()
        ident = "kLua_" + name.replace(".lua", "")
        out.append("static const unsigned char %s[] = {" % ident)
        for i in range(0, len(data), 20):
            chunk = data[i:i + 20]
            out.append("    " + ",".join(str(b) for b in chunk) + ",")
        out.append("    0};")
        out.append("static const unsigned int %s_size = %d;" % (ident, len(data)))
        out.append("")
    out.append("#endif")
    new = "\n".join(out) + "\n"
    # LF on every OS, so running this on Windows doesn't rewrite every line.
    old = open(OUT, newline="").read() if os.path.exists(OUT) else None
    if new != old:
        open(OUT, "w", newline="\n").write(new)
        print("wrote", os.path.relpath(OUT, ROOT))
    if len(sys.argv) > 1 and sys.argv[1] == "--check" and new != old:
        sys.exit("embedded_lua.h was out of date")


if __name__ == "__main__":
    main()
